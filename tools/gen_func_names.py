#!/usr/bin/env python3
"""List every recompiled function by name, for src/runtime/overlays.cpp.

Each recompiled function looks up on entry whether a mod replaced it (src/runtime/trace.h), and
knows only its own name (__func__) there; this table turns the name into the function pointer
librecomp records the replacement under.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("recompiled_dir", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    names: set[str] = set()
    for src in sorted(args.recompiled_dir.glob("funcs_*.c")):
        names.update(re.findall(r"^RECOMP_FUNC void (\w+)\(", src.read_text(), re.MULTILINE))

    lines = ["// Generated by tools/gen_func_names.py from the recompiled code.", ""]
    lines += [f'{{"{name}", {name}}},' for name in sorted(names)]
    text = "\n".join(lines) + "\n"
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if not args.out.exists() or args.out.read_text() != text:
        args.out.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
