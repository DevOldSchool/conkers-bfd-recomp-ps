#!/usr/bin/env python3
"""Render the lettering for the pause menu's SAVE and LOAD signs into
src/enhancements/pause_save/pause_sign_letters.inc.

The signs are built at runtime (src/enhancements/pause_save/pause_save.cpp): the game's own CONT...
(for SAVE) and QUIT (for LOAD) sign frames with their lettering cleared, plus these layers. Only the
lettering is stored here, so the repository keeps no ROM data. Each sign has two 64x32 RGBA layers,
dark (not selected) and bright (selected), in the style of the game's signs: filled letters, a dark
ring around them and, when bright, a glow.

Needs Pillow and numpy. Usage: tools/make_pause_signs.py [--font FILE] [--preview out.png]
"""
import argparse
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont

WIDTH, HEIGHT = 64, 32
SUPERSAMPLE = 8

# (fill, ring, glow) as RGBA; glow None for the dark variant
STYLES = {
    "dark": ((22, 75, 8, 240), (8, 25, 4, 140), None),
    "bright": ((175, 255, 40, 255), (15, 50, 0, 170), (90, 200, 10, 200)),
}
# text, point size, stroke and letter spacing in sign pixels, and the tilt of the frame it goes on
# (degrees counter-clockwise: CONT... rises to the right, QUIT falls)
SIGNS = (("SAVE", 14, 0.6, 0.5, 5.0), ("LOAD", 14, 0.6, 0.5, -5.0))


def letter_mask(font_path, text, size, stroke, spacing, angle, dx=1, dy=1):
    z = SUPERSAMPLE
    font = ImageFont.truetype(font_path, size * z)
    probe = ImageDraw.Draw(Image.new("L", (1, 1)))
    sw = int(stroke * z)
    widths = [probe.textlength(c, font=font) for c in text]
    bbox = probe.textbbox((0, 0), text, font=font, stroke_width=sw)
    width = int(sum(widths) + spacing * z * (len(text) - 1)) + 2 * sw
    height = bbox[3] - bbox[1]
    word = Image.new("L", (width + 4 * z, height + 4 * z), 0)
    draw = ImageDraw.Draw(word)
    x = 2 * z + sw
    for c, w in zip(text, widths):
        draw.text((x, 2 * z - bbox[1]), c, font=font, fill=255, stroke_width=sw, stroke_fill=255)
        x += w + spacing * z
    word = word.rotate(angle, resample=Image.BICUBIC, expand=True)
    canvas = Image.new("L", (WIDTH * z, HEIGHT * z), 0)
    canvas.paste(word, ((WIDTH * z - word.width) // 2 + dx * z, (HEIGHT * z - word.height) // 2 + dy * z), word)
    return np.asarray(canvas.resize((WIDTH, HEIGHT), Image.LANCZOS), dtype=np.float32) / 255


def layer(mask, style):
    fill, ring, glow = style
    out = np.zeros((HEIGHT, WIDTH, 4), np.float32)
    grown = np.asarray(Image.fromarray((mask * 255).astype(np.uint8)).filter(ImageFilter.MaxFilter(3)), np.float32) / 255
    out[..., :3] = ring[:3]
    out[..., 3] = grown * ring[3]
    if glow is not None:
        halo = np.asarray(Image.fromarray((mask * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.0)), np.float32) / 255
        a = np.clip(halo * glow[3] / 255, 0, 1)[..., None]
        out[..., :3] = out[..., :3] * (1 - a) + np.array(glow[:3]) * a
        out[..., 3] = np.maximum(out[..., 3], a[..., 0] * 255)
    a = mask[..., None]
    out[..., :3] = out[..., :3] * (1 - a) + np.array(fill[:3]) * a
    out[..., 3] = np.maximum(out[..., 3], mask * fill[3])
    return np.clip(out + 0.5, 0, 255).astype(np.uint8)


def main():
    root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--font", default="/System/Library/Fonts/Supplemental/Arial Rounded Bold.ttf")
    parser.add_argument("--out", type=Path, default=root / "src" / "enhancements" / "pause_save" / "pause_sign_letters.inc")
    parser.add_argument("--preview", type=Path)
    args = parser.parse_args()

    layers = {}
    for text, size, stroke, spacing, angle in SIGNS:
        mask = letter_mask(args.font, text, size, stroke, spacing, angle)
        for kind, style in STYLES.items():
            layers[f"{text} {kind}"] = layer(mask, style)

    lines = [
        "// Generated by tools/make_pause_signs.py: the pause signs' lettering, 64x32 RGBA8 rows, top first.",
        "// Order: SAVE dark, SAVE bright, LOAD dark, LOAD bright.",
    ]
    names = [f"{sign[0]} {kind}" for sign in SIGNS for kind in STYLES]
    for name in names:
        data = layers[name].tobytes()
        lines.append(f"// {name}")
        for i in range(0, len(data), 32):
            lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 32]) + ",")
    args.out.write_text("\n".join(lines) + "\n")

    if args.preview:
        sheet = Image.new("RGBA", (2 * WIDTH * 8 + 16, 2 * HEIGHT * 8 + 16), (60, 90, 40, 255))
        for i, name in enumerate(names):
            im = Image.fromarray(layers[name], "RGBA").resize((WIDTH * 8, HEIGHT * 8), Image.NEAREST)
            sheet.alpha_composite(im, ((i % 2) * (WIDTH * 8 + 16), (i // 2) * (HEIGHT * 8 + 16)))
        sheet.save(args.preview)


if __name__ == "__main__":
    main()
