#!/usr/bin/env python3
"""List the functions mods may not hook or replace, as a C++ header for src/runtime/overlays.cpp.

librecomp hooks a function by recompiling its MIPS code again with the hook calls added, and
replaces one by jumping from its start to the mod's. Neither keeps what config/us.toml changed
in the recompiled code, so these functions are locked:

* every function with a [[patches.hook]]: the hook's C++ would be lost;
* stubs: their MIPS is the TLB/exception code the recomp leaves out on purpose;
* the functions inside a shared code region (us.syms.toml `regions`): they only work as one body.

A mod can still replace a locked function with RECOMP_FORCE_PATCH, which drops the recomp's change.

It also lists the data sections (the sections with no functions), where IDO put most jump tables:
librecomp needs them to recompile a hooked function with a switch.
"""

from __future__ import annotations

import argparse
import tomllib
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True, help="config/us.toml")
    parser.add_argument("--syms", type=Path, required=True, help="config/us.syms.toml")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    config = tomllib.loads(args.config.read_text())
    syms = tomllib.loads(args.syms.read_text())

    vram_by_name: dict[str, int] = {}
    locked: dict[int, str] = {}
    for section in syms["section"]:
        functions = section.get("functions", [])
        for func in functions:
            vram_by_name[func["name"]] = func["vram"]
        for region in section.get("regions", []):
            for func in functions:
                if region["start"] <= func["vram"] < region["end"]:
                    locked.setdefault(func["vram"], f"{func['name']} (shared code region)")

    patches = config.get("patches", {})
    for name in patches.get("stubs", []):
        if name in vram_by_name:
            locked.setdefault(vram_by_name[name], f"{name} (stub)")
    for hook in patches.get("hook", []):
        name = hook["func"]
        if name not in vram_by_name:
            raise SystemExit(f"hook on {name}, which is not in {args.syms}")
        locked.setdefault(vram_by_name[name], f"{name} (hook)")

    lines = [
        "// Generated by tools/gen_mod_locks.py from config/us.toml and config/us.syms.toml.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "// The functions mods may not hook or replace (see tools/gen_mod_locks.py).",
        "constexpr uint32_t kModLockedFunctions[] = {",
    ]
    lines += [f"    {vram:#010x},  // {why}" for vram, why in sorted(locked.items())]
    lines += ["};", ""]
    lines += [
        "// The data sections, where jump tables may be: ram address, size, ROM offset (in the virtual ROM).",
        "constexpr struct {",
        "    uint32_t ram_addr, size, rom_addr;",
        "} kModJumpTableData[] = {",
    ]
    lines += [f"    {{{s['vram']:#010x}, {s['size']:#x}, {s['rom']:#x}}},  // {s['name']}"
              for s in syms["section"] if not s.get("functions")]
    lines += ["};", ""]
    text = "\n".join(lines)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if not args.out.exists() or args.out.read_text() != text:
        args.out.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
