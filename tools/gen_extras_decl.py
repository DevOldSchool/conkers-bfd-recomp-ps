#!/usr/bin/env python3
"""Declare the runtime-provided functions the recompiled code calls but funcs.h does not declare.

N64Recomp renames libultra internals it knows about to `<name>_recomp` and expects the runtime
to supply them. librecomp implements many; the rest (and libc helpers such as memcpy) are
implemented in src/runtime/ultra_extras.cpp, and the helpers that config/us.toml's hook snippets
call are in src/fixes, src/enhancements and src/credits. This script writes the matching declarations next to
the recompiler output so the generated C compiles, and lists what those files must define.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("recompiled_dir", type=Path)
    parser.add_argument("--runtime", type=Path, default=Path(__file__).resolve().parents[1] / "lib" / "N64ModernRuntime")
    src_dir = Path(__file__).resolve().parents[1] / "src"
    hook_sources = [path for folder in ("fixes", "enhancements", "credits") for path in sorted((src_dir / folder).rglob("*.cpp"))]
    parser.add_argument("--extras", type=Path, nargs="+", default=[src_dir / "runtime" / "ultra_extras.cpp", src_dir / "runtime" / "heap_check.cpp", src_dir / "runtime" / "frame_audio.cpp", src_dir / "runtime" / "frame_input.cpp", src_dir / "runtime" / "state_hash.cpp", *hook_sources])
    args = parser.parse_args()

    called: set[str] = set()
    defined: set[str] = set()
    for src in args.recompiled_dir.glob("funcs_*.c"):
        text = src.read_text()
        called.update(re.findall(r"\b(\w+)\(rdram, ctx\)", text))
        defined.update(re.findall(r"RECOMP_FUNC void (\w+)\(", text))
    declared = set(re.findall(r"void (\w+)\(uint8_t\* rdram", (args.recompiled_dir / "funcs.h").read_text()))
    called -= defined
    provided: set[str] = set()
    for src in args.runtime.glob("librecomp/src/*.cpp"):
        provided.update(re.findall(r'extern "C" void (\w+)\((?:uint8_t|RDRAM_ARG)', src.read_text()))
    for src in args.runtime.glob("ultramodern/src/*.cpp"):
        provided.update(re.findall(r'extern "C" void (\w+)\((?:uint8_t|RDRAM_ARG)', src.read_text()))

    missing = sorted(called - provided)
    header = args.recompiled_dir / "conker_extras_decl.h"
    lines = [
        "// Generated by tools/gen_extras_decl.py. Functions the recompiled code calls that the",
        "// runtime libraries do not provide; implemented in src/runtime/ultra_extras.cpp and under",
        "// src/fixes, src/enhancements and src/credits.",
        "#pragma once",
        '#include "recomp.h"',
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
    ]
    # Declare everything the generated code calls that funcs.h leaves out, whoever provides it.
    lines += [f"void {name}(uint8_t* rdram, recomp_context* ctx);" for name in sorted(called - declared)]
    lines += ["#ifdef __cplusplus", "}", "#endif", ""]
    header.write_text("\n".join(lines))

    implemented: set[str] = set()
    for src in args.extras:
        if src.exists():
            implemented.update(re.findall(r'^(?:extern "C" )?void (\w+)\(uint8_t', src.read_text(), re.M))
    unimplemented = [n for n in missing if n not in implemented]
    names = ", ".join(src.name for src in args.extras)
    print(f"{len(missing)} runtime functions needed from {names}; declarations written to {header}")
    if unimplemented:
        print(f"NOT YET IMPLEMENTED in {names}:")
        for n in unimplemented:
            print(f"  {n}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
