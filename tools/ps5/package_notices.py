#!/usr/bin/env python3
"""Writes the license files the PS5 title must carry into OUT_DIR (dist/PPSA92064/licenses).

    tools/ps5/package_notices.py OUT_DIR

tools/ps5/build.sh runs it after the package step, on the host (git describes the source there). It
writes the same four files as the desktop packages (tools/package_notices.py), for what the title
links on the console:

* LICENSE.txt: this project's own code (MIT).
* COPYING.txt: the GPL-3.0. N64ModernRuntime, Mihawk's PS5_Vulkan and payload SDK, and libc.prx are
  GPL-3.0, so the title as a whole is passed on under the GPL-3.0.
* THIRD-PARTY-NOTICES.txt: the desktop list without what the console build leaves out (the file
  dialog, router port mapping, the desktop SDL), and the console's own libraries: RADV (Mesa),
  PS5_Vulkan, the payload SDK, libc.prx and PacBrew's SDL2, libpng, bzip2 and zlib. Licenses the build
  does not keep after it is done are in tools/ps5/licenses, from the versions the build pins.
* SOURCE.txt: the exact source the title came from, and the dependencies' revisions.
"""

from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
REPO_URL = "https://github.com/DevOldSchool/conkers-bfd-recomp-ps"
UPSTREAM_URL = "https://github.com/DevOldSchool/conkers-bfd-recomp"
LICENSES = "tools/ps5/licenses"

spec = importlib.util.spec_from_file_location("package_notices", REPO / "tools/package_notices.py")
core = importlib.util.module_from_spec(spec)
sys.modules["package_notices"] = core  # its dataclass looks itself up there
spec.loader.exec_module(core)
Component = core.Component

# Not in the console build: no file dialog (a stub), no router port mapping, and PacBrew's SDL2 in
# place of the desktop one.
LEFT_OUT = ("Native File Dialog Extended", "miniupnpc", "libnatpmp", "SDL 2 (sdl2-compat")


def pins() -> dict[str, str]:
    """The dependency revisions tools/ps5/build.sh pins."""
    text = (HERE / "build.sh").read_text(encoding="utf-8")
    return dict(re.findall(r"^(ps5_\w+_(?:url|rev)|pacbrew_url)=(\S+)$", text, re.M))


def components() -> list[Component]:
    out = []
    for component in core.COMPONENTS:
        if "linux" not in component.platforms or component.name.startswith(LEFT_OUT):
            continue
        if component.name == "Monocypher":
            component = Component(component.name, component.url, component.license,
                                  (f"{LICENSES}/monocypher-LICENCE.md",))
        out.append(component)
    gpl = "The full text is in COPYING.txt."
    out += [
        Component("RADV, Mesa's Vulkan driver for AMD GPUs (Mihawk's PS5_Mesa)", "https://github.com/mihawk-99/PS5_Mesa",
                  "MIT; individual files Apache-2.0 or BSL-1.0 (each file's SPDX tag)",
                  (f"{LICENSES}/mesa-license.rst", f"{LICENSES}/mesa-MIT", f"{LICENSES}/mesa-Apache-2.0",
                   f"{LICENSES}/mesa-BSL-1.0")),
        Component("PS5_Vulkan (Mihawk): RADV's PS5 platform layer and the title's link", "https://github.com/mihawk-99/PS5_Vulkan",
                  "GPL-3.0", text=gpl),
        Component("PS5_PayloadSDK (Mihawk's fork of the PS5 payload SDK)", "https://github.com/mihawk-99/PS5_PayloadSDK",
                  "GPL-3.0; the headers in include/freebsd are under the BSD licenses each file states", text=gpl),
        Component("libc.prx (generated by ps5-native-app-boilerplate's builder, from PS5_Vulkan)",
                  "https://github.com/mihawk-99/PS5_Vulkan/tree/main/runtime",
                  "GPL-3.0-or-later", text="Copyright (C) 2026 BlackBearReloaded\n\n" + gpl),
        Component("SDL 2 (PacBrew's PS5 port)", "https://github.com/ps5-payload-dev/pacbrew-repo", "Zlib",
                  text=core.SDL_COPYRIGHT + "\n\n" + core.ZLIB),
        Component("libpng (PacBrew's PS5 port)", "http://www.libpng.org/pub/png/libpng.html", "libpng-2.0",
                  (f"{LICENSES}/libpng-LICENSE",)),
        Component("bzip2 (PacBrew's PS5 port)", "https://sourceware.org/bzip2/", "bzip2-1.0.6",
                  (f"{LICENSES}/bzip2-LICENSE",)),
        Component("zlib (PacBrew's PS5 port)", "https://zlib.net", "Zlib", (f"{LICENSES}/zlib-LICENSE",)),
    ]
    return out


def source_text(version: str) -> str:
    commit = core.git("rev-parse", "HEAD")
    dirty = bool(core.git("status", "--porcelain", "--untracked-files=no", "--ignore-submodules=all"))
    submodules = []
    for line in core.git("submodule", "foreach", "--quiet", "--recursive", 'echo "$displaypath $sha1"').splitlines():
        path, sha = line.split()
        submodules.append(f"  {path} at {sha}")
    p = pins()
    note = ""
    if dirty:
        print("package_notices.py: warning: built from uncommitted changes; SOURCE.txt says so", file=sys.stderr)
        note = ("\nThis build was made from uncommitted changes on top of that commit: it is a test build,\n"
                "not one to pass on.\n")
    return f"""Conker's Bad Fur Day Recompiled for PS5 {version}

The title's source code, under the licenses in LICENSE.txt, COPYING.txt and
THIRD-PARTY-NOTICES.txt, is at

  {REPO_URL}

(the PS5 port of {UPSTREAM_URL}). This build was made from commit

  {commit}
  {REPO_URL}/tree/{commit}
{note}
with these submodules (git submodule update --init --recursive checks them out), changed by
the patches in tools/patches (tools/apply_patches.sh applies them):

{chr(10).join(submodules)}

and these, which tools/ps5/build.sh fetches and builds at these revisions:

  {p.get('ps5_vulkan_url', '?')} at {p.get('ps5_vulkan_rev', '?')}
  {p.get('ps5_mesa_url', '?')} at {p.get('ps5_mesa_rev', '?')}
  {p.get('ps5_sdk_url', '?')} at {p.get('ps5_sdk_rev', '?')}
  PacBrew's packages: {p.get('pacbrew_url', '?')}

The build also fetches Monocypher at the version pinned in CMakeLists.txt. docs/building-ps5.md
says how to build it.

The game code is not in that source. The build makes it from your own ROM with N64Recomp
(tools/regenerate.sh). Conker's Bad Fur Day and its code, art and sound belong to Rare and
Microsoft; this project is not affiliated with or endorsed by them, or by Sony.
"""


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: tools/ps5/package_notices.py OUT_DIR")
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    version = subprocess.run([str(REPO / "tools/version.sh")], check=True, capture_output=True, text=True).stdout.strip()

    (out / "LICENSE.txt").write_text((REPO / "LICENSE").read_text(encoding="utf-8"), encoding="utf-8")
    (out / "COPYING.txt").write_text((REPO / "lib/N64ModernRuntime/COPYING").read_text(encoding="utf-8"),
                                     encoding="utf-8")
    sections = [
        "Conker's Bad Fur Day Recompiled for PS5 includes the following software. This project's own\n"
        "code is under the MIT license (LICENSE.txt). N64ModernRuntime, PS5_Vulkan, the payload SDK and\n"
        "libc.prx are under the GPL-3.0 (COPYING.txt), and since they are linked into the title or\n"
        "shipped with it, the title as a whole is passed on under the GPL-3.0. Its source code: SOURCE.txt."
    ]
    rule = "=" * 78
    for component in components():
        sections.append(f"{rule}\n{component.name}\n{component.url}\nLicense: {component.license}\n{rule}\n\n"
                        + core.license_text(component, Path("/nonexistent")))
    (out / "THIRD-PARTY-NOTICES.txt").write_text("\n\n\n".join(sections) + "\n", encoding="utf-8")
    (out / "SOURCE.txt").write_text(source_text(version), encoding="utf-8")
    print(f"==> [package] licenses and source notice in {out}")


if __name__ == "__main__":
    main()
