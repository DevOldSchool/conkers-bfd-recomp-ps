#!/usr/bin/env python3
"""Generate the data symbol file mods link against (config/us.data.syms.toml).

Mods name the game's data as the decomp (https://github.com/DevOldSchool/conkers-bfd-decomp) does.
Most of it has no curated name yet, only the address-bearing placeholder labels the disassembler
gave it (``D_800E9D00``), so this collects:

* every ``D_<address>`` label in the decomp's asm/, src/ and include/, at an address the game can
  read (RAM through KSEG0, the main alias at 0x10000000, the game and debugger images at
  0x15000000 and 0x16000000);
* the named data symbols in ``config/symbols/us.txt`` (libultra's, for now).

The data is at fixed addresses, so the file has one section with no ROM address, which
RecompModTool reads as absolute symbols. When the decomp names a placeholder, running this again
(``CONKER_UPDATE_SYMS=1 tools/regenerate.sh``) gives mods the name.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

PLACEHOLDER = re.compile(r"\bD_([0-9A-Fa-f]{8})\b")
NAMED = re.compile(r"^\s*(\w+)\s*=\s*(0x[0-9A-Fa-f]+)\s*;(.*)$")
READABLE = [
    (0x80000000, 0x80800000),  # RDRAM through KSEG0
    (0x10000000, 0x10800000),  # the main executable's TLB alias
    (0x15000000, 0x16000000),  # the game overlay image
    (0x16000000, 0x16010000),  # the debugger overlay image
]
SOURCE_SUFFIXES = {".s", ".c", ".h", ".inc"}


def readable(address: int) -> bool:
    return any(start <= address < end for start, end in READABLE)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--decomp", type=Path, default=Path(__file__).resolve().parents[2] / "conkers-bfd-decomp")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    symbols: dict[str, int] = {}
    for folder in ("asm", "src", "include"):
        for path in sorted((args.decomp / folder).rglob("*")):
            if path.suffix not in SOURCE_SUFFIXES or not path.is_file():
                continue
            for match in PLACEHOLDER.finditer(path.read_text(errors="ignore")):
                address = int(match.group(1), 16)
                if readable(address):
                    symbols[f"D_{address:08X}"] = address
    for line in (args.decomp / "config" / "symbols" / "us.txt").read_text().splitlines():
        match = NAMED.match(line)
        if match and "type:func" not in match.group(3) and readable(int(match.group(2), 16)):
            symbols[match.group(1)] = int(match.group(2), 16)

    lines = [
        "# Generated by tools/gen_data_syms.py from the conkers-bfd-decomp labels. Do not edit by hand.",
        "# The game's data for mods (mods/mod.toml's data_reference_syms_files), at fixed addresses.",
        "",
        "[[section]]",
        'name = "game_data_symbols"',
        "vram = 0x0",
        "size = 0xFFFFFFFF",
        "symbols = [",
    ]
    lines += [f'    {{ name = "{name}", vram = {address:#010x} }},'
              for name, address in sorted(symbols.items(), key=lambda item: (item[1], item[0]))]
    lines += ["]", ""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))
    print(f"{len(symbols)} data symbols in {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
