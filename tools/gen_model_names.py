#!/usr/bin/env python3
"""Write the object inspector's model names from the decomp's model registry.

The decomp's config/model-semantic-names.json gives descriptive labels to the models in the asset
banks (bank 1 holds the characters an actor's model byte picks). This writes them as a C++ table,
src/enhancements/object_inspector/model_names.inc, which is kept in the repository so a build does not
need the decomp. Run it again when the registry gains names.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def c_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def main() -> int:
    here = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--decomp", type=Path, default=here.parent / "conkers-bfd-decomp")
    parser.add_argument("--out", type=Path, default=here / "src" / "enhancements" / "object_inspector" / "model_names.inc")
    args = parser.parse_args()

    registry = json.loads((args.decomp / "config" / "model-semantic-names.json").read_text())
    models = sorted(registry["models"], key=lambda m: (m["bank"], m["entry"], m["segment"]))
    lines = [
        "// Generated by tools/gen_model_names.py from the decomp's config/model-semantic-names.json",
        f"// ({registry['name_kind']}, {registry['profile']} ROM). {{bank, entry, segment, name}}",
    ]
    for model in models:
        lines.append(f"{{{model['bank']}, {model['entry']}, {model['segment']}, {c_string(model['name'])}}},")
    args.out.write_text("\n".join(lines) + "\n")
    print(f"{len(models)} names -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
